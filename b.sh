# 四、ERC4626 专项审计要点

## 虚拟份额机制
- OZ v5 的 `_convertToShares` 使用 `totalSupply() + 10**_decimalsOffset()` 和 `totalAssets() + 1`
- 虚拟份额 = `10**_decimalsOffset()`，虚拟资产 = `1`，两者不对称是设计使然
- 虚拟份额的本质是"硬编码初始兑换率"，保证 decimals 对齐 + 防通胀攻击

## 通胀攻击（无虚拟份额时）
- 攻击者 deposit 2 wei → 捐赠大量资产 → 受害者存款被 Floor 到极小 shares → 攻击者赎回拿走大部分资产
- 虚拟份额让攻击者初始份额变为 `2 * 10^offset`，受害者不会被 Floor 到接近 0
- 审计时必须验证 `_decimalsOffset()` 返回值是否等于 `vaultDecimals - assetDecimals`

## 舍入方向
- `previewDeposit` → Floor（对协议有利）
- `previewMint` → Ceil（对协议有利）
- `previewWithdraw` → Ceil（对协议有利）
- `previewRedeem` → Floor（对协议有利）
- 确认所有公开预览函数使用的舍入方向正确

## Wrapper 场景（Vault 包装 AMM/LP）
- 如果 ERC4626 Vault 的底层资产是 Uniswap V2/V3 position，必须审计 `totalAssets()` 的 override 实现
- `totalAssets()` 的折算逻辑如果依赖可被操纵的价格源（spot price、balanceOf(pool)），就会重新引入通胀攻击
- 正确做法：用 TWAP、预言机、或 position 自身 tick 范围内的 liquidity 计算，不读全局池子余额

