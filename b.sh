## 找漏洞的思维

# 一、核心审计思维模型

## 1.1 外部可操控性——所有 DeFi 漏洞的根源

**一个本该由合约自己决定状态的计算，被外部输入影响了。**

审计每个函数时，必须执行以下检查链：
1. **识别经济边界**：这个函数的计算结果会不会影响"钱"（铸币、兑换率、清算、费用、奖励）？
2. **追溯输入源**：计算结果依赖的变量，有没有任何一个可以被外部地址通过转账、swap、捐赠、闪电贷、重入、抢跑等方式操控？
3. **判定隔离性**："可被操控的输入"和"决定钱的计算"之间有没有被安全隔离（如 TWAP、预言机、虚拟基数、访问控制）？
4. **构造攻击路径**：如果隔离不足，攻击者具体怎么操作才能获利？给出精确的数学推导，不要估算。

**判断标准不是"有没有读外部"，而是"读外部的结果有没有经济后果"。**
- `balanceOf(pool)` 只读展示 → 没风险
- `balanceOf(pool)` 用来算 `totalAssets()` → 影响铸币 → 有风险

## 1.2 逆向构造——找漏洞的核心方法

遇到门控条件，不要视其为不可逾越的墙，而把它当成"待伪造的前提"，反推需要先控制、构造或污染什么，再一步步实现。

- **正面受阻则走侧面**：合约受限则考虑链下（oracle、relayer、keeper、admin 操作、前端逻辑等），逻辑受限则利用时序或经济激励
- **优先关注存在依赖关系的项目**：若 A 依赖 B，或 B 依赖 A，应重点审查可被操纵以间接控制 A/B 的路径
- **重点盯防合约无条件信任的外部依赖**，从薄弱处下手

> 注：逆向构造不是替代"外部可操控性"框架，而是它的战术补充——当顺着代码正向追踪找不到突破口时，切到"我要让这个条件成立，需要先污染什么"的反向视角。

## 1.3 依赖追踪与合约身份识别

- 所有依赖关系、信任边界、外部调用，必须以源码、构建配置或官方文档为证，不得假设
- **合约身份先行**：对任意地址做行为分析前，先确认其合约类型（proxy / wrapper / adapter / implementation）
- 若为中间层合约，必须递归向下追踪，直到找到真正产出数据的非代理合约为止
- **挖到底的判定标准**：每调用一个外部函数，都要追问"该函数内部 call 了哪个地址？该地址的合约类型是什么？"只有抵达非 proxy、非 wrapper、自行维护状态的合约（如 OCR2Aggregator 的 oraclenodes）才可视为终点
- **构造器参数必须验证**：任何影响安全属性的参数（heartbeat、decimals、maxSlippage、staleThreshold 等）必须在链上读取 view 值并报告。例如 heartbeat=0 会使 staleness 检查实质失效，属于典型参数绕过类漏洞

